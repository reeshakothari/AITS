// Writes supabase/seed.sql from src/content/*.json so the database starts with the current site content.
// Run: node scripts/gen-seed.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = 'src/content';
const rows = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => {
    const key = f.replace(/\.json$/, '');
    const json = JSON.stringify(JSON.parse(readFileSync(`${dir}/${f}`, 'utf8')));
    if (json.includes('$aits$')) throw new Error(`${f} contains the SQL quote tag $aits$`);
    return `  ('${key}', 'draft', $aits$${json}$aits$::jsonb),\n  ('${key}', 'published', $aits$${json}$aits$::jsonb)`;
  });

const sql = `-- Generated by scripts/gen-seed.mjs. Seeds draft and published content; existing rows are left alone.
insert into public.aits_site_content (key, status, data) values
${rows.join(',\n')}
on conflict (key, status) do nothing;
`;
writeFileSync('supabase/seed.sql', sql);
console.log(`Wrote supabase/seed.sql with ${rows.length} content keys.`);
